/** Translate a UI string for the given locale. Unknown keys fall back to the Chinese source. */
export function translate(locale: UiLocale, source: string): string {
  if (locale !== "en") return source;
  return EN_DICT[source] ?? source;
}

/** Substitute `{name}` placeholders after translation. */
export function translateWithVars(
  locale: UiLocale,
  source: string,
  vars: Record<string, string | number>
): string {
  const out = translate(locale, source);
  return out.replace(/\{(\w+)\}/g, (match, name) =>
    name in vars ? String(vars[name]) : match
  );
}

/** Bind `translate` to a fixed locale. */
export function makeT(locale: UiLocale) {
  return (source: string): string => translate(locale, source);
}

/**
 * 启用 / 停用 double as status words ("Enabled") and action words ("Enable").
 * The base dictionary uses the action reading; badges override to the status
 * reading so an English status pill never reads like a button label.
 */
const EN_BADGE_OVERRIDES: Record<string, string> = {
  启用: "Active",
  停用: "Disabled",
};

export function translateBadge(locale: UiLocale, source: string): string {
  if (locale !== "en") return source;
  return EN_BADGE_OVERRIDES[source] ?? translate(locale, source);
}

export function makeBadgeT(locale: UiLocale) {
  return (source: string): string => translateBadge(locale, source);
}

/** Like `makeT` but supports `{name}` placeholders. */
export function makeTv(locale: UiLocale) {
  return (source: string, vars: Record<string, string | number>): string =>
    translateWithVars(locale, source, vars);
}

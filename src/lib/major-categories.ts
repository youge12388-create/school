/** 判断一条文本是否为非专业的噪音条目 */
export function isMajorNoise(entry: string): boolean {
  const trimmed = entry.trim();
  if (trimmed.length < 2 || trimmed.length > 30) return true;
  return NOISE_PATTERNS.some((pattern) => pattern.test(trimmed));
}

/**
 * 把单个专业名归类到 12 大类之一
 * 按数组顺序匹配，先命中先归；未命中返回 null（归入"其他"）
 */
export function categorizeMajor(major: string): MajorCategoryKey | null {
  const text = major.trim();
  if (!text) return null;
  for (const cat of MAJOR_CATEGORIES) {
    if (cat.keywords.some((keyword) => text.includes(keyword))) {
      return cat.key;
    }
  }
  return null;
}

/** 把专业列表按大类分组的结果 */
export type CategorizedMajors = {
  categories: { key: MajorCategoryKey; label: string; majors: string[] }[];
  others: string[];
};

/**
 * 把专业列表清洗 + 按大类分组
 * 同一个专业只归入第一个命中的大类，避免重复
 */
export function categorizeMajors(majors: string[]): CategorizedMajors {
  const seen = new Set<string>();
  const byCategory = new Map<MajorCategoryKey, string[]>();
  const others: string[] = [];

  for (const raw of majors) {
    const trimmed = raw.trim();
    if (!trimmed || isMajorNoise(trimmed)) continue;
    const normalized = trimmed.toLowerCase();
    if (seen.has(normalized)) continue;
    seen.add(normalized);

    const cat = categorizeMajor(trimmed);
    if (cat) {
      const list = byCategory.get(cat) ?? [];
      list.push(trimmed);
      byCategory.set(cat, list);
    } else {
      others.push(trimmed);
    }
  }

  const categories = MAJOR_CATEGORIES.map((cat) => ({
    key: cat.key,
    label: cat.label,
    majors: (byCategory.get(cat.key) ?? []).sort((a, b) =>
      a.localeCompare(b, "zh-CN"),
    ),
  })).filter((cat) => cat.majors.length > 0);

  others.sort((a, b) => a.localeCompare(b, "zh-CN"));

  return { categories, others };
}

/** 把项目 major_text 字段切分成专业条目列表 */
export function splitMajorText(majorText: string | null | undefined): string[] {
  if (!majorText) return [];
  return majorText
    .split(/[\n;；,，、]+/u)
    .map((entry) => entry.trim())
    .filter(Boolean);
}

/**
 * 按大类名（label）反查该大类的关键词列表。
 * 用于 matcher 里"query 是大类名"时的快捷匹配。
 * 找不到返回 null。
 */
export function getMajorKeywordsByLabel(
  label: string,
): readonly string[] | null {
  const trimmed = label.trim();
  const cat = MAJOR_CATEGORIES.find((c) => c.label === trimmed);
  return cat ? cat.keywords : null;
}
